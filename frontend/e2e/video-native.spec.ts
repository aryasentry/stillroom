import {test,expect} from '@playwright/test';
import path from 'node:path';
import fs from 'node:fs/promises';

test('native video extracts frames and reconstructs a locally accepted room',async({page})=>{
  test.skip(process.env.STILLROOM_TEST_NATIVE_VIDEO!=='1','Long native video reconstruction is opt-in');
  test.setTimeout(30*60*1000);
  const title='Synthetic video reconstructed locally',started=Date.now(),external:string[]=[],errors:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',async route=>{const url=route.request().url();if(url.startsWith('http')&&!url.startsWith('http://127.0.0.1:8850/')){external.push(url);await route.abort()}else await route.continue()});
  await page.goto('/');await page.getByRole('button',{name:'Create a room from photos',exact:true}).click();
  await page.getByLabel('Place name',{exact:true}).fill(title);
  await page.getByLabel('Choose room video',{exact:true}).setInputFiles(path.resolve('..','fixtures','capture-room-video.mp4'));
  await page.getByLabel('Target video frames').selectOption('80');
  await page.getByRole('button',{name:'Extract frames from video',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Video frames ready',exact:true})).toBeVisible({timeout:120000});
  const summaries=await(await page.request.get('/api/projects')).json(),id=summaries.find((p:any)=>p.title===title).id;
  const getProject=async()=>await(await page.request.get(`/api/projects/${id}`)).json();
  const extracted=await getProject(),extraction=(await(await page.request.get(`/api/projects/${id}/video-extractions`)).json())[0];
  expect(extraction.frameCount).toBeGreaterThanOrEqual(40);expect(extraction.frameCount).toBeLessThanOrEqual(80);
  expect(extracted.room.scanAssetId).toBeNull();
  const sources=extracted.assets.filter((a:any)=>a.role==='capture');
  expect(sources.every((a:any)=>a.metadata.videoFrame?.sourceAssetId===extraction.sourceAssetId)).toBe(true);
  await page.screenshot({path:path.resolve('..','docs/evidence/video-extracted-frames.png'),fullPage:true});
  await page.getByLabel('Reconstruction quality',{exact:true}).selectOption('preview');
  await page.getByRole('button',{name:'Create a room from photos',exact:true}).click();
  const job=async()=> (await(await page.request.get(`/api/projects/${id}/reconstructions`)).json())[0];
  await expect.poll(async()=>{const j=await job();if(!j)return 'starting';if(['failed','needs_photos','interrupted','cancelled'].includes(j.status))throw new Error(JSON.stringify(j));return j.status},{timeout:25*60*1000,intervals:[3000]}).toBe('ready');
  const ready=await job();expect(ready.iteration).toBe(ready.totalIterations);expect(ready.registeredPhotos).toBeGreaterThanOrEqual(30);
  await page.getByRole('button',{name:'Preview reconstructed room',exact:false}).click();
  await expect(page.locator('.reconstruction-preview canvas')).toBeVisible();
  await expect(page.getByRole('button',{name:'Use this room',exact:true})).toBeEnabled({timeout:60000});
  await page.screenshot({path:path.resolve('..','docs/evidence/video-reconstruction-preview.png'),fullPage:true});
  await page.getByRole('button',{name:'Use this room',exact:true}).click();
  await expect(page.locator('.room-topbar h1')).toHaveText(title);
  await expect(page.locator('.room-viewer canvas')).toBeVisible();await expect(page.locator('.room-viewer-message')).toHaveCount(0);
  const accepted=await getProject(),scan=accepted.assets.find((a:any)=>a.id===ready.resultAssetId);
  expect(accepted.room.scanAssetId).toBe(ready.resultAssetId);expect(accepted.room.sceneType).toBe('splat');
  expect(scan.metadata.reconstruction.sourceImages).toHaveLength(extraction.frameCount);
  const archive=await page.request.get(`/api/projects/${id}/export`);expect(archive.ok()).toBe(true);
  await fs.writeFile(path.resolve('..','fixtures/stillroom-video-demo.zip'),await archive.body());
  expect(external).toEqual([]);expect(errors).toEqual([]);
  await fs.writeFile(path.resolve('..','docs/evidence/video-browser-verification.json'),JSON.stringify({elapsedSeconds:(Date.now()-started)/1000,extraction,job:ready,scan,sourceVideo:extracted.assets.find((a:any)=>a.id===extraction.sourceAssetId),projectId:id,browserExternalRequests:external,browserErrors:errors,fixture:'H.264 clip encoded from the CC0 synthetic camera sequence; not a physical room recording',realRoomTested:false},null,2));
});
